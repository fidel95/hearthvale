import { readFileSync, writeFileSync } from 'node:fs'
import { it } from 'vitest'
import { worksheet, type BuildingRow, type CropRow } from '../src/game/balance'

// npm run balance: writes the balancing worksheet, worked out from the game's
// catalogs, into docs/BALANCE.md (between the "generated" markers), and as
// JSON and CSV files for spreadsheets.

const n = (v: number | null, digits = 1) => (v === null ? '—' : Number.isInteger(v) ? v.toLocaleString('en-US') : v.toFixed(digits))
const time = (s: number | null) => (s === null ? '—' : s === 0 ? 'instant' : s < 3600 ? `${Math.round(s / 60 * 10) / 10} min` : `${s / 3600} h`)

function table(headers: string[], rows: (string | number)[][]): string {
  return [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')
}

function csv(rows: object[]): string {
  const keys = Object.keys(rows[0])
  const cell = (v: unknown) => {
    const s = Array.isArray(v) ? v.join('; ') : v === null ? '' : String(v)
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }
  return [keys.join(','), ...rows.map((r) => keys.map((k) => cell((r as Record<string, unknown>)[k])).join(','))].join('\n') + '\n'
}

it('writes the balance worksheet', () => {
  const w = worksheet()
  const byKindThenLevel = (a: BuildingRow, b: BuildingRow) => a.category.localeCompare(b.category) || a.unlockLevel - b.unlockLevel
  const earners = w.buildings.filter((b) => b.cycleSeconds !== null).sort(byKindThenLevel)
  const support = w.buildings.filter((b) => b.cycleSeconds === null).sort(byKindThenLevel)

  const md = [
    `_Generated by \`npm run balance\` from the game's catalogs. Assumptions: income collected as soon as it's ready, full utilities, no location bonus, before tax; a shop's goods valued at ${n(w.assumptions.goodCost)} coins each (the cheapest shipment); shops get ${n(w.assumptions.goodRetail)} per good._`,
    '',
    '### Levels and what each one introduces',
    '',
    table(
      ['Level', 'Total XP', 'New mechanic', 'Unlocks', 'Quests needing this level'],
      w.levels.map((l) => [l.level, n(l.totalXp), l.newMechanics.join(', ') || '—', l.unlocks.join(', ') || '—', l.quests.join(', ') || '—']),
    ),
    '',
    '### Buildings that earn',
    '',
    table(
      ['Building', 'Role', 'Level', 'Size', 'Cost', 'Materials', 'Build', 'Cycle', 'Per cycle', 'Goods', 'Net', 'XP', 'Residents', 'Payback', 'Coins/min', 'Upgrades', 'Quests'],
      earners.map((b: BuildingRow) => [
        b.name,
        b.role,
        b.unlockLevel,
        b.footprint,
        n(b.cost),
        b.materials ? `${b.materials} (${n(b.materialsValue)})` : '—',
        time(b.buildSeconds),
        time(b.cycleSeconds),
        n(b.coinsPerCycle),
        b.goodsPerCycle || '—',
        n(b.netPerCycle),
        `${b.xpPerCycle} (+${b.buildXp} to build)`,
        b.residents || '—',
        `${n(b.paybackCycles)} cycles · ${n(b.paybackMinutes)} min`,
        n(b.coinsPerMinute),
        b.upgrades,
        b.quests.join(', ') || '—',
      ]),
    ),
    '',
    'Payback cycles = (coins + materials) ÷ net coins per cycle. Payback minutes adds the build time. No building needs a road; homes and shops beside one earn +5%.',
    '',
    '### Buildings that support the town',
    '',
    table(
      ['Building', 'Role', 'Level', 'Size', 'Cost', 'Materials', 'Build', 'Effect', 'Uses', 'Runs per month', 'XP to build', 'Quests'],
      support.map((b: BuildingRow) => [
        b.name,
        b.role,
        b.unlockLevel,
        b.footprint,
        n(b.cost),
        b.materials ? `${b.materials} (${n(b.materialsValue)})` : '—',
        time(b.buildSeconds),
        b.effect || '—',
        b.needs || '—',
        b.upkeepPerMonth ? n(b.upkeepPerMonth) : '—',
        b.buildXp,
        b.quests.join(', ') || '—',
      ]),
    ),
    '',
    '### Crops',
    '',
    table(
      ['Crop', 'Role', 'Level', 'Seeds', 'Grows', 'Fresh for', 'Market price', 'Or goods', 'Profit', 'Profit/min', 'XP', 'Coins/energy', 'Plot paid back in'],
      w.crops.map((c: CropRow) => [
        c.name,
        c.role,
        c.unlockLevel,
        n(c.seedCost),
        time(c.growSeconds),
        time(c.freshSeconds),
        n(c.marketPrice),
        `📦 ${c.goods} (worth ${n(c.goodsValue)} in shops)`,
        n(c.profitPerCycle),
        n(c.profitPerMinute),
        c.xp,
        n(c.coinsPerEnergy),
        `${n(c.plotPaybackHarvests, 2)} harvests`,
      ]),
    ),
    '',
    '### Energy',
    '',
    `A full bar at level 1 is ${w.energy.maxAtLevel1} ⚡ and refills ${n(w.energy.regenPerMinute)} a minute. Collecting from three cottages and tending a strawberry plot uses about ${n(w.energy.usePerMinute)} a minute, so a full bar lasts about ${n(w.energy.minutesOfActivePlay)} minutes of nonstop tapping, and early level-ups refill it.`,
  ].join('\n')

  const path = 'docs/BALANCE.md'
  const doc = readFileSync(path, 'utf8')
  const start = '<!-- generated:start -->'
  const end = '<!-- generated:end -->'
  const before = doc.slice(0, doc.indexOf(start) + start.length)
  const after = doc.slice(doc.indexOf(end))
  writeFileSync(path, `${before}\n\n${md}\n\n${after}`)
  writeFileSync('docs/balance.json', JSON.stringify(w, null, 2) + '\n')
  writeFileSync('docs/balance-buildings.csv', csv(w.buildings))
  writeFileSync('docs/balance-crops.csv', csv(w.crops))
})
